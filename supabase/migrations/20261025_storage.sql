-- Private application schema: Telegram authorization remains in FastAPI.
CREATE SCHEMA IF NOT EXISTS skinsavo;
SET LOCAL search_path TO skinsavo, pg_catalog;
REVOKE ALL ON SCHEMA skinsavo FROM PUBLIC;

CREATE TABLE IF NOT EXISTS users (
    telegram_id TEXT PRIMARY KEY,
    username TEXT NOT NULL DEFAULT '',
    balance NUMERIC NOT NULL DEFAULT 0 CHECK (balance >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    first_name TEXT NOT NULL DEFAULT '', last_name TEXT NOT NULL DEFAULT '',
    photo_url TEXT NOT NULL DEFAULT '', language_code TEXT NOT NULL DEFAULT '',
    is_premium SMALLINT NOT NULL DEFAULT 0, last_login_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS skins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL, weapon TEXT NOT NULL, skin TEXT NOT NULL,
    rarity TEXT NOT NULL, condition TEXT NOT NULL,
    price NUMERIC NOT NULL CHECK (price >= 0), stock BIGINT NOT NULL CHECK (stock >= 0),
    image TEXT NOT NULL, description TEXT NOT NULL, active SMALLINT NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS balance_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id TEXT NOT NULL REFERENCES users(telegram_id), amount NUMERIC NOT NULL,
    event_type TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id TEXT NOT NULL REFERENCES users(telegram_id), skin_id BIGINT NOT NULL REFERENCES skins(id),
    name TEXT NOT NULL, price NUMERIC NOT NULL, status TEXT NOT NULL DEFAULT 'owned',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS bot_sessions (
    telegram_id TEXT PRIMARY KEY, mode TEXT NOT NULL, value TEXT NOT NULL DEFAULT '',
    expires_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id TEXT NOT NULL REFERENCES users(telegram_id), message_id BIGINT NOT NULL,
    body TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open', reply TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, answered_at TIMESTAMPTZ,
    UNIQUE(telegram_id, message_id)
);
CREATE TABLE IF NOT EXISTS telegram_updates (
    update_id BIGINT PRIMARY KEY, payload TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
    owner_id TEXT NOT NULL DEFAULT '', attempts INTEGER NOT NULL DEFAULT 0,
    available_at DOUBLE PRECISION NOT NULL DEFAULT 0, claimed_at DOUBLE PRECISION NOT NULL DEFAULT 0,
    last_error TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS storage_migrations (
    source_id TEXT PRIMARY KEY, fingerprint TEXT NOT NULL, row_counts TEXT NOT NULL,
    completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS inventory_owner ON inventory(telegram_id,id);
CREATE INDEX IF NOT EXISTS history_owner ON balance_events(telegram_id,id);
CREATE INDEX IF NOT EXISTS support_owner ON support_tickets(telegram_id,id);
CREATE INDEX IF NOT EXISTS telegram_pending ON telegram_updates(status,available_at,update_id);
CREATE INDEX IF NOT EXISTS telegram_owner ON telegram_updates(owner_id,update_id,status);

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE skins ENABLE ROW LEVEL SECURITY;
ALTER TABLE balance_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory ENABLE ROW LEVEL SECURITY;
ALTER TABLE bot_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE support_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE telegram_updates ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage_migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA skinsavo FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA skinsavo FROM PUBLIC;
DO $$
DECLARE role_name TEXT;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
            EXECUTE format('REVOKE ALL ON SCHEMA skinsavo FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA skinsavo FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA skinsavo FROM %I', role_name);
        END IF;
    END LOOP;
END $$;
